    /** 61 mini puzzles: one per day for two months before the cycle repeats. */
    val dailyMini: List<Puzzle> = listOf(mini6) + miniData.map { parsePuzzle(6, 2, 3, it) }

    /** 31 classic puzzles. */
    val classic: List<Puzzle> = listOf(classic9) + classicData.map { parsePuzzle(9, 3, 3, it) }

    fun dailyMiniFor(date: LocalDate): Puzzle =
        dailyMini[Math.floorMod(date.toEpochDay(), dailyMini.size.toLong()).toInt()]

    fun classicFor(date: LocalDate): Puzzle =
        classic[Math.floorMod(date.toEpochDay(), classic.size.toLong()).toInt()]

    private fun parsePuzzle(size: Int, boxRows: Int, boxCols: Int, encoded: String): Puzzle {
        val cells = size * size
        check(encoded.length == cells * 2) { "bad puzzle data length: ${encoded.length}" }
        return Puzzle(
            size = size,
            boxRows = boxRows,
            boxCols = boxCols,
            givens = encoded.take(cells).map { it.digitToInt() },
            solution = encoded.drop(cells).map { it.digitToInt() },
        )
    }
